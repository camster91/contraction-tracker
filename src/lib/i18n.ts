export type MessageKey = keyof typeof messages.en;
const frMessages = { ...frCore, ...frSharing, ...frJourney } satisfies Record<MessageKey, string>;
let activeLocale: MessageLocale = 'en';

export function getMessageCatalog(locale: SupportedLocale): Readonly<Record<MessageKey, string>> {
  return locale === 'fr-CA' ? frMessages : messages.en;
}

export function getLocale(): MessageLocale { return activeLocale; }

const RTL_LANGUAGES = new Set(['ar', 'fa', 'he', 'ps', 'ur']);

export function getTextDirection(locale: string): 'ltr' | 'rtl' {
  try {
    const info = (new Intl.Locale(locale) as Intl.Locale & { textInfo?: { direction?: string } }).textInfo;
    if (info?.direction === 'rtl') return 'rtl';
    if (info?.direction === 'ltr') return 'ltr';
  } catch { /* use the language fallback */ }
  const language = locale.toLowerCase().split(/[-_]/)[0];
  return RTL_LANGUAGES.has(language) ? 'rtl' : 'ltr';
}

const PSEUDO_ACCENTS: Record<string, string> = {
  a: 'à', A: 'À', b: 'ƀ', B: 'Ɓ', c: 'ç', C: 'Ç', d: 'đ', D: 'Đ',
  e: 'ë', E: 'Ë', f: 'ƒ', F: 'Ƒ', g: 'ğ', G: 'Ğ', h: 'ħ', H: 'Ħ',
  i: 'ï', I: 'Ï', j: 'ĵ', J: 'Ĵ', k: 'ķ', K: 'Ķ', l: 'ľ', L: 'Ľ',
  m: 'ɱ', M: 'Ṁ', n: 'ñ', N: 'Ñ', o: 'ô', O: 'Ô', p: 'þ', P: 'Þ',
  q: 'ɋ', Q: 'Ɋ', r: 'ř', R: 'Ř', s: 'š', S: 'Š', t: 'ŧ', T: 'Ŧ',
  u: 'ü', U: 'Ü', v: 'ṽ', V: 'Ṽ', w: 'ŵ', W: 'Ŵ', x: 'ẋ', X: 'Ẋ',
  y: 'ÿ', Y: 'Ÿ', z: 'ž', Z: 'Ž',
};

export function pseudoLocalize(value: string): string {
  const accented = [...value].map((character) => PSEUDO_ACCENTS[character] ?? character).join('');
  const expansion = ' ·'.repeat(Math.max(2, Math.ceil(value.length * 0.18)));
  return `［${accented}${expansion}］`;
}

/** Message copy is English-only today, but dates/numbers should still follow
 * the device's display locale. Invalid locale tags safely fall back to en. */
export function getDisplayLocale(candidates?: readonly string[]): string {
  const requested = candidates ?? (typeof navigator !== 'undefined'
    ? (navigator.languages?.length ? navigator.languages : [navigator.language])
    : []);
  for (const candidate of requested) {
    if (!candidate) continue;
    try {
      return new Intl.DateTimeFormat(candidate).resolvedOptions().locale;
    } catch { /* try the next device locale */ }
  }
  return 'en';
}

export function setLocale(locale: string): MessageLocale {
  const available = [...SUPPORTED_LOCALES, ...PSEUDO_LOCALES] as readonly string[];
  activeLocale = available.includes(locale) ? locale as MessageLocale : 'en';
  if (typeof document !== 'undefined') {
    document.documentElement.lang = activeLocale;
    document.documentElement.dir = getTextDirection(activeLocale);
  }
  return activeLocale;
}

export function setPreferredLocale(locale: string): MessageLocale {
  const selected = setLocale(locale);
  if (typeof localStorage !== 'undefined') {
    try { localStorage.setItem('olive:message-locale', selected); } catch { /* keep the in-memory choice */ }
  }
  return selected;
}

export function t(key: MessageKey, values: Readonly<Record<string, string | number>> = {}): string {
  const template = activeLocale === 'fr-CA' ? frMessages[key] : messages.en[key];
  if (activeLocale === 'en' || activeLocale === 'fr-CA') return template.replace(/\{(\w+)\}/g, (placeholder, name: string) => (
    Object.hasOwn(values, name) ? String(values[name]) : placeholder
  ));
  // Pseudo-localize only catalog-authored copy. Interpolated values may be
  // names, notes, codes, or other user-owned text and must remain untouched.
  const tokens: string[] = [];
  const masked = template.replace(/\{(\w+)\}/g, (placeholder, name: string) => {
    if (!Object.hasOwn(values, name)) return placeholder;
    const token = `\uFFF0${tokens.length}\uFFF1`;
    tokens.push(String(values[name]));
    return token;
  });
  return pseudoLocalize(masked).replace(/\uFFF0(\d+)\uFFF1/g, (_match, index: string) => tokens[Number(index)] ?? '');
}

export type LocalizedJourneyPhase = 'preparing' | 'labor' | 'postpartum' | 'archived';

export function getJourneyHero(phase: LocalizedJourneyPhase): { eyebrow: string; title: string; detail: string } {
  const keys = {
    preparing: ['journey.hero.preparing.eyebrow', 'journey.hero.preparing.title', 'journey.hero.preparing.detail'],
    labor: ['journey.hero.labor.eyebrow', 'journey.hero.labor.title', 'journey.hero.labor.detail'],
    postpartum: ['journey.hero.postpartum.eyebrow', 'journey.hero.postpartum.title', 'journey.hero.postpartum.detail'],
    archived: ['journey.hero.archived.eyebrow', 'journey.hero.archived.title', 'journey.hero.archived.detail'],
  } as const;
  const [eyebrow, title, detail] = keys[phase];
  return { eyebrow: t(eyebrow), title: t(title), detail: t(detail) };
}

export function formatLocalizedDateTime(value: string | Date, options?: Intl.DateTimeFormatOptions, locale = getDisplayLocale()): string {
  const date = value instanceof Date ? value : new Date(value);
  return new Intl.DateTimeFormat(locale, options ?? { dateStyle: 'medium', timeStyle: 'short' }).format(date);
}

export function formatLocalizedNumber(value: number, options?: Intl.NumberFormatOptions): string {
  return new Intl.NumberFormat(getDisplayLocale(), options).format(value);
}

export function pluralCategory(value: number): Intl.LDMLPluralRule {
  const locale = activeLocale === 'en-XA' ? 'en' : activeLocale === 'ar-XB' ? 'ar' : activeLocale;
  return new Intl.PluralRules(locale).select(value);
}

export function formatLocalizedUnit(value: number, unit: Intl.NumberFormatOptions['unit']): string {
  return new Intl.NumberFormat(getDisplayLocale(), { style: 'unit', unit, unitDisplay: 'short' }).format(value);
}

function initialMessageLocale(): string {
  if (typeof window === 'undefined') return 'en';
  try {
    return localStorage.getItem('olive:internal-message-locale')
      ?? localStorage.getItem('olive:message-locale')
      ?? (navigator.language?.toLowerCase().startsWith('fr') ? 'fr-CA' : 'en');
  } catch { return 'en'; }
}

setLocale(initialMessageLocale());
